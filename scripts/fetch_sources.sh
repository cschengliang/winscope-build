#!/usr/bin/env bash
# Fetch only the AOSP pieces Winscope needs, laid out like an AOSP tree.
# Usage: scripts/fetch_sources.sh [AOSP_REF] [OUT_DIR]
#   AOSP_REF: branch or tag used for every repo (default: main), e.g. android-16.0.0_r1
#   OUT_DIR : AOSP-like root (default: ./aosp)
set -euo pipefail
REF="${1:-${AOSP_REF:-main}}"
TOP="${2:-${AOSP_TOP:-$PWD/aosp}}"
BASE_URL="${AOSP_MIRROR:-https://android.googlesource.com}"

sparse() {  # sparse <dest> <repo> <paths...>   (no paths = full checkout)
  local dest="$TOP/$1" repo="$2"; shift 2
  echo "::group::$repo @ $REF -> $dest"
  rm -rf "$dest"; mkdir -p "$dest"
  git -C "$dest" init -q
  git -C "$dest" remote add origin "$BASE_URL/$repo"
  if [ "$#" -gt 0 ]; then git -C "$dest" sparse-checkout set --no-cone "$@"; fi
  git -C "$dest" fetch -q --depth 1 --filter=blob:none origin "$REF"
  git -C "$dest" checkout -q FETCH_HEAD
  echo "$repo $(git -C "$dest" rev-parse HEAD)" >> "$TOP/SOURCES.txt"
  echo "::endgroup::"
}

mkdir -p "$TOP"; : > "$TOP/SOURCES.txt"
# Winscope itself
sparse development                 platform/development                  '/tools/winscope/'
# Window manager / IME / shell transition protos (+ their imports)
sparse frameworks/base             platform/frameworks/base              '/core/proto/' '/libs/WindowManager/Shell/proto/'
# ViewCapture proto
sparse frameworks/libs/systemui    platform/frameworks/libs/systemui     '/viewcapturelib/src/com/android/app/viewcapture/proto/'
# Enums imported by frameworks/base view protos
sparse frameworks/proto_logging    platform/frameworks/proto_logging     '/stats/enums/'
# SurfaceFlinger / transactions / protolog / input / transitions protos, and the trace processor (wasm)
# (full checkout: Winscope's TS imports protos generated by the Perfetto UI build)
sparse external/perfetto           platform/external/perfetto
echo "Sources:"; cat "$TOP/SOURCES.txt"
